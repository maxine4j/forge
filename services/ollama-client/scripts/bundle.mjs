import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { build } from "esbuild";

const outfile = "dist/forge-ollama-client.cjs";
const result = await build({
	entryPoints: ["src/worker-main.ts"],
	bundle: true,
	platform: "node",
	target: "node24",
	format: "cjs",
	minify: true,
	lineLimit: 120,
	legalComments: "eof",
	banner: { js: "// Generated by pnpm bundle. See services/ollama-client/README.md." },
	outfile,
	metafile: true,
	write: false,
});

const packages = new Map();
for (const input of Object.keys(result.metafile.outputs[outfile].inputs)) {
	const match = /^(.*\/node_modules\/((?:@[^/]+\/)?[^/]+))\//u.exec(input);
	if (match) packages.set(match[1], match[2]);
}
const notices = await Promise.all(
	[...packages.keys()].sort().map(async (directory) => {
		const license = (await readdir(directory)).find((name) => /^licen[cs]e(?:\.|$)/iu.test(name));
		if (!license) throw new Error(`Missing license for ${packages.get(directory)}`);
		const text = await readFile(join(directory, license), "utf8");
		return `${packages.get(directory)}\n${text.trim()}`;
	}),
);
const comments = notices
	.join("\n\n")
	.split("\n")
	.map((line) => `// ${line}`.trimEnd())
	.join("\n");
await mkdir("dist", { recursive: true });
await writeFile(outfile, `${result.outputFiles[0].text}\n${comments}\n`);
